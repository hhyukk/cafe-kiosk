package com.cafekiosk.support;

import java.time.Duration;
import java.util.List;

/**
 * 동시 실행 하네스가 한 판 돌고 내놓는 결과다.
 *
 * ── 실패를 필드로 두지 않는 이유 ────────────────────────────────────────────────
 *
 * 실패 건수는 예외들.size() 로 언제나 계산되므로 따로 들고 있을 이유가 없다.
 * 필드로 두면 둘이 어긋난 상태를 만들 수 있고, 그 어긋남은 동시성 테스트에서 가장
 * 다루기 나쁜 종류의 거짓말이다. 성공 3 실패 7 이라고 말하는데 예외 목록에 6 개만
 * 들어 있으면, 읽는 사람은 락을 의심하기 전에 어느 쪽이 참인지부터 알아내야 한다.
 *
 * ── 실패수(Class) 가 이 record 의 존재 이유다 ───────────────────────────────────
 *
 * 재고 3 에 10 스레드를 던지면 총 실패는 7 이어야 한다. 그런데 총 실패 7 은 락이
 * 동작한다는 근거가 되지 못한다. 커넥션 풀 고갈로 죽은 스레드와 재고가 부족해서
 * 거절당한 스레드가 섞여도 합은 7 이 될 수 있기 때문이다.
 * OutOfStockException 이 정확히 7 건이라고 말할 수 있어야 락 이야기를 할 수 있다.
 *
 * ── 재시도가 합류했다 ──────────────────────────────────────────────────────────
 *
 * 이 자리는 낙관적 락 단계까지 비어 있었다. 재시도를 세는 주체가 없는데 필드부터 만들면
 * 세 전략에서 언제나 0 인 열이 생기고, 그 0 이 재시도가 없었다는 뜻인지 세지 않았다는
 * 뜻인지 읽는 사람이 구분할 수 없기 때문이었다.
 *
 * 이제 OrderFacade 가 재시도 횟수를 돌려주므로 그 구분이 생겼다. 비관적 락과 분산 락에서
 * 이 값이 0 인 것은 재시도가 실제로 없었다는 뜻이다. 잠근 채로 읽으니 버전이 어긋날
 * 일이 없다. 낙관적 락에서만 0 보다 크고, 그 숫자가 잠그지 않고 읽은 대가다.
 *
 * 세는 것은 성공한 스레드의 재시도뿐이다. 실패한 스레드가 쓴 시도를 같은 열에 섞으면
 * 이 숫자가 무엇의 비용인지 흐려진다. 실패는 이미 예외들이 따로 들고 있다.
 */
public record ConcurrencyResult(int 성공, List<Throwable> 예외들, int 재시도, Duration 소요시간) {

    public ConcurrencyResult {
        // 하네스가 넘긴 큐를 그대로 들고 있으면 결과를 받아 본 뒤에도 내용이 바뀔 수 있다.
        예외들 = List.copyOf(예외들);
    }

    public int 실패() {
        return 예외들.size();
    }

    /**
     * 특정 타입으로 실패한 건수를 센다. 상속 관계를 포함한다.
     */
    public long 실패수(Class<? extends Throwable> 타입) {
        return 예외들.stream().filter(타입::isInstance).count();
    }

    /**
     * 세 전략 비교표의 재료다. 예외 목록은 넣지 않는다.
     * 스레드 10 개가 각자 스택 트레이스를 들고 있으면 정작 봐야 할 숫자가 묻힌다.
     *
     * 이 한 줄이 빨간불 출력에 그대로 찍히고, 그 줄을 PR 본문에 옮기면 비교표의 한 행이 된다.
     */
    public String 요약() {
        return "성공 %d, 실패 %d, 재시도 %d, 소요 %d ms".formatted(성공, 실패(), 재시도, 소요시간.toMillis());
    }
}
