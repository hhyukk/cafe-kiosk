package com.cafekiosk.stock.lock;

import com.cafekiosk.stock.entity.Stock;

/**
 * 재고 행을 확보하는 방법을 갈아 끼우는 자리다.
 *
 * 이 프로젝트는 같은 동시성 테스트를 비관적 락, 낙관적 락, 분산 락 셋에 차례로 걸고
 * 어느 쪽이 언제 유리한지를 말이 아니라 성공 건수와 재시도 횟수로 비교한다. NFR-CON-03.
 * 그러려면 전략을 바꿀 때 OrderService 를 고치지 않아도 되어야 한다.
 *
 * ── 메서드가 하나뿐인 이유 ────────────────────────────────────────────────────
 *
 * 세 전략은 사실 서로 다른 층에서 논다. 비관적 락은 트랜잭션 안에서 행을 잠그고,
 * 낙관적 락의 재시도는 롤백된 트랜잭션 밖에서 일어나야 하며, 분산 락은 트랜잭션을 감싼다.
 * 그래서 이 인터페이스 하나로 셋을 다 덮으려 들면 어딘가에서 거짓말을 하게 된다.
 *
 * 여기서는 트랜잭션 안쪽 seam 만 판다. 바깥에서 감싸는 자리는 얇은 파사드가 맡을 텐데,
 * 그건 낙관적 락 단계가 실제로 재시도를 넣을 때 만든다. 지금 파 두면 비어 있는 채로 남는다.
 *
 * ── 확보한다는 말이 전략마다 다른 일을 뜻한다 ─────────────────────────────────
 *
 * 비관적 락에서는 SELECT ... FOR UPDATE 로 다른 트랜잭션을 멈춰 세우는 일이다.
 * 낙관적 락에서는 그냥 읽는 일이고, 어긋남은 커밋 시점에 버전이 잡는다.
 * 분산 락에서는 Redis 에서 열쇠를 받아 온 뒤 읽는 일이다.
 * 호출자는 어느 쪽이든 깎아도 되는 Stock 을 받았다는 것만 알면 된다.
 *
 * ── 확보한 다음에 무엇을 하는지는 이 인터페이스가 정하지 않는다 ───────────────
 *
 * 차감 규칙은 계속 Stock 엔티티가 소유한다. decrease 와 increase 는 락을 세 번
 * 갈아 끼우는 동안 한 글자도 바뀌지 않아야 한다. 그래야 세 전략 사이의 차이를
 * 락 때문이라고 말할 수 있다. 여기가 바뀌면 무엇을 비교한 것인지 알 수 없게 된다.
 */
public interface StockLockStrategy {

    /**
     * 차감하거나 복구할 재고 행을 확보한다. 재고 행이 없으면 StockNotFoundException 이다.
     *
     * 호출자는 활성 트랜잭션 안에 있어야 한다. 지금 부르는 곳은 OrderService 의
     * createOrder 와 changeStatus 둘뿐이고 둘 다 @Transactional 이다.
     */
    Stock acquire(Long menuId);
}
