package com.cafekiosk.order.facade;

/**
 * 재시도를 거쳐 나온 결과와 그 값을 얻기까지 몇 번 다시 시도했는지를 함께 담는다.
 *
 * retries 는 시도 횟수가 아니라 재시도 횟수다. 한 번에 성공하면 0 이다.
 * 세 전략을 비교할 때 읽을 숫자가 시도가 아니라 낭비된 시도라서 그렇다.
 *
 * ── 카운터 빈에 쌓지 않는 이유 ──────────────────────────────────────────────────
 *
 * OrderFacade 에 AtomicLong 을 하나 두고 거기 누적시키는 방법도 있다. 호출자가
 * 반환값을 풀지 않아도 되므로 컨트롤러가 깔끔해진다. 그런데 그 값은 테스트 사이에 샌다.
 * 어느 테스트가 만든 숫자인지 가르려면 초기화 메서드를 프로덕션 코드에 열어야 하고,
 * 그 메서드는 테스트만 부르는 메서드가 된다.
 *
 * 더 나쁜 것은 동시성 테스트가 그 값을 읽는 시점이다. 스레드 열 개가 각자 누적하는
 * 동안 테스트 스레드가 읽으면 언제 읽었느냐에 따라 다른 값이 나온다. 반환값으로
 * 돌려주면 각 스레드가 자기 몫만 들고 나오므로 그 창이 없다.
 *
 * ── 값이 없는 호출에는 Void 를 담는다 ──────────────────────────────────────────
 *
 * changeStatus 는 돌려줄 것이 없다. RetryResult<Void> 에 null 을 담는다.
 * 재시도 횟수만 필요한 자리를 위해 별도 타입을 하나 더 만들지 않는다.
 */
public record RetryResult<T>(T value, int retries) {
}
